export const getAppBySlug = (slug: string) =>
  CATALOG.find((a) => a.slug === slug);

export const topApps = () =>
  CATALOG.filter((a) => a.kind === "app" && a.chartRank).sort(
    (a, b) => a.chartRank! - b.chartRank!,
  );

export const topGames = () =>
  CATALOG.filter((a) => a.kind === "game" && a.chartRank).sort(
    (a, b) => a.chartRank! - b.chartRank!,
  );

export const featuredApps = () => CATALOG.filter((a) => a.badge);

export const appsByCategory = (category: string) =>
  CATALOG.filter((a) => a.category === category);

export const searchCatalog = (query: string) => {
  const q = query.trim().toLowerCase();
  if (!q) return CATALOG;
  return CATALOG.filter(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      a.developer.toLowerCase().includes(q) ||
      a.category.toLowerCase().includes(q) ||
      a.tags.some((t) => t.includes(q)),
  );
};
